#!/usr/bin/env python3
"""
scripts/pin_image_digests.py — BUILD_LOG Journey 377 (pingdin_platform);
copied VERBATIM into pingdin_observability (its BUILD_LOG Journey 8) because
the two repos deploy independently to different servers and this repo is
deliberately self-contained. Keep the two copies identical: a fix to one is a
fix to both.

Real gap found while auditing the observability layer: `docker-compose.yml`
pins `postgres`, `redis`, and `caddy` to a fixed major version, but
Alloy, and every metrics exporter (postgres-exporter, redis-exporter,
cadvisor, node-exporter) still float on `:latest` — and
`deployment-templates/docker-compose.sovereign-{a,b}.yml` carry the same
`litellm:main-stable` floating tag. `pingdin_observability`'s own repo
already paid for exactly this once (its BUILD_LOG's own Grafana 12.2.0
story — `:latest` floated onto a real, confirmed regression, and the fix
was pinning to the one version already known to work). Nothing here
guesses which NEWER version to move to — that risks introducing an
untested behavior change of its own. Instead: capture the digest of
whatever is ALREADY running on this server right now. That can never
change behavior (it's the exact bits already live), and it stops a future
`docker compose pull` from silently swapping in a different build under
the same floating tag.

USAGE (on the deploy server, after `docker compose up -d`):
    python3 scripts/pin_image_digests.py [path/to/docker-compose.yml]

Reads the compose file's own `services:` block (no hardcoded service or
image list — this repo's own standing "config/registry-driven, no
hardcoded values" discipline applies here too, and it's what keeps this
script correct against deployment-templates/*.yml without a second copy).
For every service with an `image:` key, runs `docker inspect` against
that service's own `container_name` to find the exact digest Docker
already resolved for the container that is running right now, and prints
a ready-to-paste `image:` replacement line. Services built from a local
Dockerfile (`build:`, no `image:` key — pingdin-core/-edge/-compute/
-alert-bridge) have nothing to pin here; their own reproducibility is the
`requirements.txt` pins and the Python base image tag, a different
concern. Read-only: never modifies docker-compose.yml or any container.
"""

from __future__ import annotations

import re
import subprocess
import sys

try:
    import yaml
except ImportError:
    print("error: PyYAML is required (pip install pyyaml)", file=sys.stderr)
    raise SystemExit(1)

# Tags known to float onto a different build over time without the tag
# itself changing. Anything NOT matching one of these (postgres:16,
# caddy:2, grafana/grafana:12.1.1, ...) is treated as already pinned.
_FLOATING_TAG_RE = re.compile(r":(latest|main|main-stable|edge|nightly)$")


def is_floating_tag(image: str) -> bool:
    """True if `image`'s tag is a known-floating channel, or if it has no
    tag at all (Docker then defaults to `:latest`, the same risk)."""
    if _FLOATING_TAG_RE.search(image):
        return True
    last_segment = image.rsplit("/", 1)[-1]
    return ":" not in last_segment


def load_services(compose_path: str) -> dict:
    with open(compose_path, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    return (data or {}).get("services", {}) or {}


def running_digest(container_name: str) -> str | None:
    """The `repo@sha256:...` reference for the image THIS container is
    running right now — not a fresh pull, so it can never disagree with
    what is already live. Returns None if the container isn't running or
    Docker isn't reachable from here (e.g. this script run outside the
    deploy server, or before `docker compose up`)."""
    try:
        image_id = subprocess.run(
            ["docker", "inspect", "--format", "{{.Image}}", container_name],
            capture_output=True, text=True, check=True, timeout=10,
        ).stdout.strip()
        if not image_id:
            return None
        digest = subprocess.run(
            ["docker", "image", "inspect", image_id, "--format", "{{index .RepoDigests 0}}"],
            capture_output=True, text=True, check=True, timeout=10,
        ).stdout.strip()
        return digest or None
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired, FileNotFoundError):
        return None


def main(argv: list[str]) -> int:
    compose_path = argv[1] if len(argv) > 1 else "docker-compose.yml"
    try:
        services = load_services(compose_path)
    except FileNotFoundError:
        print(f"error: {compose_path} not found", file=sys.stderr)
        return 1
    if not services:
        print(f"error: no services found in {compose_path}", file=sys.stderr)
        return 1

    print(f"# Generated by scripts/pin_image_digests.py against {compose_path}")
    print("# Paste each `image:` line below over the matching service's own —")
    print("# every digest is the exact image already running on THIS server,")
    print("# so pasting it changes nothing about what's deployed, only whether")
    print("# a future `docker compose pull` can silently change it.\n")

    any_floating = False
    any_unreachable = False
    for name, svc in sorted(services.items()):
        image = svc.get("image")
        if not image:
            continue  # built locally (build:/dockerfile:) — nothing to pin here
        floating = is_floating_tag(image)
        if not floating:
            continue  # already pinned; only report what needs attention
        any_floating = True
        container = svc.get("container_name", name)
        digest = running_digest(container)
        if digest:
            print(f"# {name} (currently {image})")
            print(f"  image: {digest}\n")
        else:
            any_unreachable = True
            print(f"# {name} (currently {image}) — could not read a running digest;"
                  f" is the '{container}' container up, and is Docker reachable from here?\n")

    if not any_floating:
        print("Every service's image is already pinned — nothing to do.")
    elif any_unreachable:
        print("Some services above need the stack running (`docker compose up -d`)"
              " and this script run ON the deploy server, not elsewhere.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
